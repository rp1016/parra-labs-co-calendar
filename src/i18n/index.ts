export type MessageKey = keyof typeof es;

const dictionaries: Record<Language, Record<MessageKey, string>> = { es, en };

export function translate(
  language: Language,
  key: MessageKey,
  params?: Record<string, string | number>,
): string {
  const template = dictionaries[language][key] ?? es[key] ?? key;
  if (!params) return template;
  return Object.entries(params).reduce(
    (text, [name, value]) => text.replaceAll(`{${name}}`, String(value)),
    template,
  );
}

export function useT() {
  const language = useAppStore((state) => state.data.settings.language);
  return useCallback(
    (key: MessageKey, params?: Record<string, string | number>) => translate(language, key, params),
    [language],
  );
}

export function localeOf(language: Language): string {
  return language === "es" ? "es-ES" : "en-US";
}
